# sum with a start, round with digits, three-argument pow, reversed on strings and ranges
print(sum([1, 2, 3], 10))
print(sum([0.5, 0.25], 1))
print(sum([], 0))
print(round(3.14159, 2), round(2.5), round(3.5), round(-0.5))
print(round(1234, -2), round(1250, -2))
print(round(2.675, 2))
print(pow(3, 4, 5), pow(2, 10, 1000))
print(divmod(7.5, 2), divmod(-7, 2))
print(list(reversed("abc")))
print("".join(reversed("abc")))
print(list(reversed(range(5))))
print(list(reversed([1, 2, 3])))
for ch in reversed("xy"):
    print(ch)
print(list(enumerate(reversed([1, 2]))))
print(sum(x * x for x in range(4)))
print(max(range(5)), min(range(3, 6)))
print(sum(range(101)))
print(len(list(zip(range(3), range(10)))))
